import { ZodError } from "zod";
import { localEdit } from "@/lib/local-editor";
import { buildEditMessages } from "@/lib/prompts";
import {
  callChat,
  extractJsonObject,
  isAiConfigured,
} from "@/lib/provider";
import { clientKey, rateLimit } from "@/lib/rate-limit";
import { applyScenePatch, PatchError } from "@/lib/scene-patcher";
import { EditRequestSchema, formatZodError } from "@/lib/scene-schema";

export const runtime = "nodejs";
export const maxDuration = 60;

const jsonHeaders = { "Cache-Control": "no-store" };
const FALLBACK_SUGGESTIONS = [
  "Add a second shelter to the west",
  "Reroute residents to the west shelter",
  "Add a bridge north of the causeway",
  "Close Market Road",
];

function errorMessage(error: unknown): string {
  if (error instanceof ZodError) return formatZodError(error);
  if (error instanceof Error) return error.message.slice(0, 400);
  return "Unknown edit error";
}

function applyLocal(
  plan: ReturnType<typeof EditRequestSchema.parse>["plan"],
  prompt: string,
  selectedId: string | undefined,
  fallbackNotice?: string,
): Response {
  const result = localEdit(plan, prompt, selectedId);
  if (!result.supported) {
    return Response.json(
      {
        error: result.reason,
        suggestions: result.suggestions,
        mode: "local",
      },
      { status: 422, headers: jsonHeaders },
    );
  }
  try {
    const applied = applyScenePatch(plan, { operations: result.operations });
    return Response.json(
      {
        plan: applied.plan,
        operations: applied.operations,
        summary: applied.summary,
        mode: fallbackNotice ? "fallback" : "local",
        notice:
          fallbackNotice ??
          "Applied by WorldOps' deterministic local editor. No AI model was called.",
      },
      { headers: jsonHeaders },
    );
  } catch (error) {
    const message =
      error instanceof PatchError ? error.message : "The local patch was invalid.";
    return Response.json(
      { error: message, suggestions: FALLBACK_SUGGESTIONS, mode: "local" },
      { status: 422, headers: jsonHeaders },
    );
  }
}

export async function POST(request: Request): Promise<Response> {
  const limit = rateLimit(clientKey(request, "edit"), 20, 60_000);
  if (!limit.allowed) {
    return Response.json(
      { error: `Too many edits. Try again in ${limit.retryAfterSeconds}s.` },
      { status: 429, headers: jsonHeaders },
    );
  }

  let bodyText: string;
  try {
    bodyText = await request.text();
  } catch {
    return Response.json({ error: "Could not read the request." }, { status: 400, headers: jsonHeaders });
  }
  if (bodyText.length > 300_000) {
    return Response.json({ error: "Request is too large." }, { status: 413, headers: jsonHeaders });
  }

  let body: unknown;
  try {
    body = JSON.parse(bodyText);
  } catch {
    return Response.json({ error: "Invalid JSON body." }, { status: 400, headers: jsonHeaders });
  }

  const parsed = EditRequestSchema.safeParse(body);
  if (!parsed.success) {
    return Response.json(
      { error: formatZodError(parsed.error) },
      { status: 400, headers: jsonHeaders },
    );
  }

  const { plan, prompt, selectedId, tick } = parsed.data;

  if (!isAiConfigured()) {
    return applyLocal(plan, prompt, selectedId);
  }

  let correction: string | undefined;
  let lastError: unknown;

  for (let attempt = 0; attempt < 2; attempt += 1) {
    try {
      const text = await callChat(
        buildEditMessages(plan, prompt, selectedId, tick, correction),
      );
      const payload = extractJsonObject(text) as {
        operations?: unknown;
        unsupported_request?: unknown;
        reason?: unknown;
      };

      if (payload.unsupported_request === true) {
        return Response.json(
          {
            error:
              typeof payload.reason === "string"
                ? payload.reason.slice(0, 240)
                : "This edit cannot be represented with the supported operations.",
            suggestions: FALLBACK_SUGGESTIONS,
            mode: "ai",
          },
          { status: 422, headers: jsonHeaders },
        );
      }

      if (!Array.isArray(payload.operations)) {
        throw new PatchError("invalid_patch", "The model did not return an operations array.");
      }

      const applied = applyScenePatch(plan, { operations: payload.operations });
      return Response.json(
        {
          plan: applied.plan,
          operations: applied.operations,
          summary: applied.summary,
          mode: "ai",
          notice: "Edit generated by AI, validated, then applied by WorldOps.",
        },
        { headers: jsonHeaders },
      );
    } catch (error) {
      lastError = error;
      correction = errorMessage(error);
      console.error(`[edit-scene] attempt ${attempt + 1} failed: ${correction}`);
    }
  }

  console.error("[edit-scene] AI edit failed", lastError);
  const fallback = applyLocal(
    plan,
    prompt,
    selectedId,
    "The AI edit failed, so WorldOps applied the deterministic local editor instead.",
  );
  if (fallback.ok) return fallback;

  return Response.json(
    {
      error:
        "The AI edit service is unavailable and the local editor could not interpret that request. Try a simpler edit.",
      suggestions: FALLBACK_SUGGESTIONS,
      mode: "fallback",
    },
    { status: 502, headers: jsonHeaders },
  );
}
