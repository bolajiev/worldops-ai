import { chromium } from 'playwright';
const executablePath = process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE || undefined;
const browser = await chromium.launch({ headless: true, executablePath, args: ['--no-sandbox','--use-gl=angle','--use-angle=swiftshader','--disable-dev-shm-usage'] });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 }, deviceScaleFactor: 1 });
const errors=[];
page.on('console',m=>{ if(m.type()==='error' && !m.text().includes('favicon') && !m.text().includes('synchronously unmount')) errors.push(m.text().slice(0,200)); });
page.on('pageerror',e=>errors.push('PAGEERROR: '+e.message.slice(0,200)));
await page.goto('http://localhost:3002', { waitUntil: 'domcontentloaded', timeout: 180000 });
await page.waitForFunction(() => !!window.__worldopsStore, null, { timeout: 180000 });
await page.waitForSelector('canvas', { timeout: 120000 });
await page.waitForTimeout(5000);
await page.evaluate(() => { const o=window.__worldops; if(o){ o.gl.shadowMap.enabled=false; o.gl.setPixelRatio(1); o.gl.setSize(window.innerWidth, window.innerHeight, false); } document.querySelectorAll('nextjs-portal').forEach(e=>e.remove()); });
await page.waitForTimeout(2000);
console.log('initial', await page.locator('.app-shell').evaluate(el=>({...el.dataset})));
await page.screenshot({ path: 'qa-artifacts/20-initial.png', timeout: 180000 });
await page.evaluate(() => { const s=window.__worldopsStore; s.getState().start(); for(let i=0;i<46;i++) s.getState().tick(); });
await page.waitForTimeout(2500);
console.log('running', await page.locator('.app-shell').evaluate(el=>({...el.dataset})));
await page.screenshot({ path: 'qa-artifacts/21-running.png', timeout: 180000 });
console.log('errors', errors.slice(0,6));
await browser.close();
