import { chromium } from 'playwright';
const executablePath = process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE || undefined;
const browser = await chromium.launch({ headless: true, executablePath, args: ['--no-sandbox','--disable-gpu','--disable-webgl','--disable-webgl2','--disable-dev-shm-usage'] });
const page = await browser.newPage({ viewport: { width: 1280, height: 800 } });
const errors = [];
page.on('console', m => { if (m.type()==='error' && !m.text().includes('favicon') && !m.text().includes('WebGL') && !m.text().includes('synchronously unmount')) errors.push(m.text().slice(0,200)); });
page.on('pageerror', e => errors.push('PAGEERROR: '+e.message.slice(0,200)));
const stats = () => page.locator('.app-shell').evaluate(el => ({...el.dataset}));
const ticks = async n => { await page.evaluate(count => { const s = window.__worldopsStore; for(let i=0;i<count;i++) s.getState().tick(); }, n); await page.waitForTimeout(1500); };
await page.goto('http://localhost:3002', { waitUntil: 'domcontentloaded', timeout: 180000 });
await page.waitForFunction(() => !!window.__worldopsStore, null, { timeout: 180000 });
console.log('hydrated');
await page.waitForTimeout(1500);
console.log('initial', await stats());
await page.evaluate(() => document.querySelector('button[aria-label="Start simulation"]')?.click());
await ticks(46);
console.log('running', await stats());
const skiff = page.locator('.risk-row button:has-text("Skiff")').first();
console.log('skiff visible', await skiff.count(), 'enabled', await skiff.isEnabled().catch(()=>false));
await skiff.evaluate(el => el.click());
await page.waitForTimeout(800);
console.log('after dispatch', await stats(), (await page.locator('.toast').innerText().catch(()=>''))); 
await ticks(140);
console.log('result', await stats());
await page.evaluate(() => document.querySelector('button[aria-label="Reset simulation"]')?.click());
await page.waitForTimeout(800);
console.log('reset', await stats());
await page.evaluate(() => { const tab=[...document.querySelectorAll('[role="tab"]')].find(el=>el.textContent.includes('Edit live world')); if(tab instanceof HTMLElement) tab.click(); });
await page.waitForTimeout(500);
await page.locator('#edit-prompt').fill('Add a second shelter to the west and reroute residents');
await page.evaluate(() => { const b=[...document.querySelectorAll('button')].find(el=>el.textContent.includes('Apply edit')); if(b instanceof HTMLElement) b.click(); });
await page.waitForSelector('.applied-box', { timeout: 120000 });
console.log('edited', await stats());
console.log('summary', (await page.locator('.applied-box').innerText()).replace(/\n/g,' | ').slice(0,200));
await page.evaluate(() => { const tab=[...document.querySelectorAll('[role="tab"]')].find(el=>el.textContent.includes('Event log')); if(tab instanceof HTMLElement) tab.click(); });
await page.waitForTimeout(500);
console.log('log visible', await page.locator('.log-row').count());
console.log('errors', errors.slice(0,8));
await browser.close();
